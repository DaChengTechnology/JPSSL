#!/usr/bin/env python3
"""Simulate donna's fexpand and fcontract to check roundtrip"""
p = 2**255 - 19

def fexpand(s):
    """Donna-style fexpand: bytes -> 10 limbs"""
    h = [0]*10
    h[0] = s[0] | (s[1]<<8) | (s[2]<<16) | (s[3]<<24)
    h[1] = (s[4] | (s[5]<<8) | (s[6]<<16)) << 6
    h[2] = (s[7] | (s[8]<<8) | (s[9]<<16)) << 5
    h[3] = (s[10] | (s[11]<<8) | (s[12]<<16)) << 3
    h[4] = (s[13] | (s[14]<<8) | (s[15]<<16)) << 2
    h[5] = s[16] | (s[17]<<8) | (s[18]<<16) | (s[19]<<24)
    h[6] = (s[20] | (s[21]<<8) | (s[22]<<16)) << 7
    h[7] = (s[23] | (s[24]<<8) | (s[25]<<16)) << 5
    h[8] = (s[26] | (s[27]<<8) | (s[28]<<16)) << 4
    h[9] = ((s[29] | (s[30]<<8) | (s[31]<<16)) & 0x7fffff) << 2
    return h

def freduce_coefficients(h):
    """Donna freduce_coefficients"""
    c = (h[9] + (1<<24)) >> 25; h[0] += c * 19; h[9] -= c << 25
    c = (h[1] + (1<<24)) >> 25; h[2] += c; h[1] -= c << 25
    c = (h[3] + (1<<24)) >> 25; h[4] += c; h[3] -= c << 25
    c = (h[5] + (1<<24)) >> 25; h[6] += c; h[5] -= c << 25
    c = (h[7] + (1<<24)) >> 25; h[8] += c; h[7] -= c << 25
    c = (h[0] + (1<<25)) >> 26; h[1] += c; h[0] -= c << 26
    c = (h[2] + (1<<25)) >> 26; h[3] += c; h[2] -= c << 26
    c = (h[4] + (1<<25)) >> 26; h[5] += c; h[4] -= c << 26
    c = (h[6] + (1<<25)) >> 26; h[7] += c; h[6] -= c << 26
    c = (h[8] + (1<<25)) >> 26; h[9] += c; h[8] -= c << 26

def fcontract(h):
    """Donna fcontract: limbs -> bytes"""
    for _ in range(2):
        c = (h[9] + (1<<24)) >> 25; h[0] += c * 19; h[9] -= c << 25
        c = (h[7] + (1<<24)) >> 25; h[8] += c; h[7] -= c << 25
        c = (h[5] + (1<<24)) >> 25; h[6] += c; h[5] -= c << 25
        c = (h[3] + (1<<24)) >> 25; h[4] += c; h[3] -= c << 25
        c = (h[1] + (1<<24)) >> 25; h[2] += c; h[1] -= c << 25
        c = (h[8] + (1<<25)) >> 26; h[9] += c; h[8] -= c << 26
        c = (h[6] + (1<<25)) >> 26; h[7] += c; h[6] -= c << 26
        c = (h[4] + (1<<25)) >> 26; h[5] += c; h[4] -= c << 26
        c = (h[2] + (1<<25)) >> 26; h[3] += c; h[2] -= c << 26
        c = (h[0] + (1<<25)) >> 26; h[1] += c; h[0] -= c << 26
    
    s = [0]*32
    s[0] = h[0] & 0xFF
    s[1] = (h[0] >> 8) & 0xFF
    s[2] = (h[0] >> 16) & 0xFF
    s[3] = ((h[0] >> 24) | (h[1] << 2)) & 0xFF
    s[4] = (h[1] >> 6) & 0xFF
    s[5] = (h[1] >> 14) & 0xFF
    s[6] = ((h[1] >> 22) | (h[2] << 3)) & 0xFF
    s[7] = (h[2] >> 5) & 0xFF
    s[8] = (h[2] >> 13) & 0xFF
    s[9] = ((h[2] >> 21) | (h[3] << 5)) & 0xFF
    s[10] = (h[3] >> 3) & 0xFF
    s[11] = (h[3] >> 11) & 0xFF
    s[12] = ((h[3] >> 19) | (h[4] << 7)) & 0xFF
    s[13] = (h[4] >> 1) & 0xFF
    s[14] = (h[4] >> 9) & 0xFF
    s[15] = (h[4] >> 17) & 0xFF
    s[16] = ((h[4] >> 25) | (h[5] << 6)) & 0xFF
    s[17] = (h[5] >> 2) & 0xFF
    s[18] = (h[5] >> 10) & 0xFF
    s[19] = (h[5] >> 18) & 0xFF
    s[20] = ((h[5] >> 26) | (h[6] << 4)) & 0xFF
    s[21] = (h[6] >> 4) & 0xFF
    s[22] = (h[6] >> 12) & 0xFF
    s[23] = ((h[6] >> 20) | (h[7] << 6)) & 0xFF
    s[24] = (h[7] >> 2) & 0xFF
    s[25] = (h[7] >> 10) & 0xFF
    s[26] = (h[7] >> 18) & 0xFF
    s[27] = ((h[7] >> 26) | (h[8] << 5)) & 0xFF
    s[28] = (h[8] >> 3) & 0xFF
    s[29] = (h[8] >> 11) & 0xFF
    s[30] = ((h[8] >> 19) | (h[9] << 7)) & 0xFF
    s[31] = (h[9] >> 1) & 0xFF
    return bytes(s)

# Test roundtrip
import random
random.seed(42)
for t in range(5):
    orig = bytes([random.randint(0,255) for _ in range(32)])
    h = fexpand(orig)
    freduce_coefficients(h)
    out = fcontract(h)
    ok = orig == out
    print(f"Roundtrip {t}: {'OK' if ok else 'FAIL'}")
    if not ok:
        print(f"  in: {orig.hex()}")
        print(f" out: {out.hex()}")
