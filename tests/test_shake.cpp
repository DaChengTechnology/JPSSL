// SHAKE 测试向量 (NIST FIPS 202 KAT，经 hashlib shake_128/256 现场验证)
// 验证 SHAKE128/256 XOF 正确性，为 Ed448 提供依赖保证
#include "sha3.hpp"
#include <cstdio>
#include <cstring>

static void print_hex(const char* label, const uint8_t* data, size_t len) {
    printf("%s: ", label);
    for (size_t i = 0; i < len; i++) printf("%02x", data[i]);
    printf("\n");
}

static bool check(const char* name, const uint8_t* got, const uint8_t* exp, size_t n) {
    bool ok = memcmp(got, exp, n) == 0;
    printf("[%s] %s\n", ok ? "PASS" : "FAIL", name);
    if (!ok) { print_hex("  Got     ", got, n); print_hex("  Expected", exp, n); }
    return ok;
}

int main() {
    bool all = true;

    // ---- SHAKE128 empty 32B
    {
        uint8_t out[32];
        jpssl::shake128(nullptr, 0, out, 32);
        static const uint8_t exp[32] = {
            0x7f,0x9c,0x2b,0xa4,0xe8,0x8f,0x82,0x7d,0x61,0x60,0x45,0x50,0x76,0x05,0x85,0x3e,
            0xd7,0x3b,0x80,0x93,0xf6,0xef,0xbc,0x88,0xeb,0x1a,0x6e,0xac,0xfa,0x66,0xef,0x26
        };
        all &= check("SHAKE128 empty 32B", out, exp, 32);
    }

    // ---- SHAKE256 empty 32B
    {
        uint8_t out[32];
        jpssl::shake256(nullptr, 0, out, 32);
        static const uint8_t exp[32] = {
            0x46,0xb9,0xdd,0x2b,0x0b,0xa8,0x8d,0x13,0x23,0x3b,0x3f,0xeb,0x74,0x3e,0xeb,0x24,
            0x3f,0xcd,0x52,0xea,0x62,0xb8,0x1b,0x82,0xb5,0x0c,0x27,0x64,0x6e,0xd5,0x76,0x2f
        };
        all &= check("SHAKE256 empty 32B", out, exp, 32);
    }

    // ---- SHAKE256 empty 64B (跨 squeeze block 边界，rate=136)
    {
        uint8_t out[64];
        jpssl::shake256(nullptr, 0, out, 64);
        static const uint8_t exp[64] = {
            0x46,0xb9,0xdd,0x2b,0x0b,0xa8,0x8d,0x13,0x23,0x3b,0x3f,0xeb,0x74,0x3e,0xeb,0x24,
            0x3f,0xcd,0x52,0xea,0x62,0xb8,0x1b,0x82,0xb5,0x0c,0x27,0x64,0x6e,0xd5,0x76,0x2f,
            0xd7,0x5d,0xc4,0xdd,0xd8,0xc0,0xf2,0x00,0xcb,0x05,0x01,0x9d,0x67,0xb5,0x92,0xf6,
            0xfc,0x82,0x1c,0x49,0x47,0x9a,0xb4,0x86,0x40,0x29,0x2e,0xac,0xb3,0xb7,0xc4,0xbe
        };
        all &= check("SHAKE256 empty 64B", out, exp, 64);
    }

    // ---- SHAKE256("abc") 32B (非空输入验证吸收逻辑)
    {
        uint8_t out[32];
        static const uint8_t in[3] = {'a','b','c'};
        jpssl::shake256(in, 3, out, 32);
        static const uint8_t exp[32] = {
            0x48,0x33,0x66,0x60,0x13,0x60,0xa8,0x77,0x1c,0x68,0x63,0x08,0x0c,0xc4,0x11,0x4d,
            0x8d,0xb4,0x45,0x30,0xf8,0xf1,0xe1,0xee,0x4f,0x94,0xea,0x37,0xe7,0x8b,0x57,0x39
        };
        all &= check("SHAKE256(abc) 32B", out, exp, 32);
    }

    // ---- SHAKE256 empty 114B (Ed448 核心依赖长度)
    {
        uint8_t out[114];
        jpssl::shake256(nullptr, 0, out, 114);
        static const uint8_t exp[114] = {
            0x46,0xb9,0xdd,0x2b,0x0b,0xa8,0x8d,0x13,0x23,0x3b,0x3f,0xeb,0x74,0x3e,0xeb,0x24,
            0x3f,0xcd,0x52,0xea,0x62,0xb8,0x1b,0x82,0xb5,0x0c,0x27,0x64,0x6e,0xd5,0x76,0x2f,
            0xd7,0x5d,0xc4,0xdd,0xd8,0xc0,0xf2,0x00,0xcb,0x05,0x01,0x9d,0x67,0xb5,0x92,0xf6,
            0xfc,0x82,0x1c,0x49,0x47,0x9a,0xb4,0x86,0x40,0x29,0x2e,0xac,0xb3,0xb7,0xc4,0xbe,
            0x14,0x1e,0x96,0x61,0x6f,0xb1,0x39,0x57,0x69,0x2c,0xc7,0xed,0xd0,0xb4,0x5a,0xe3,
            0xdc,0x07,0x22,0x3c,0x8e,0x92,0x93,0x7b,0xef,0x84,0xbc,0x0e,0xab,0x86,0x28,0x53,
            0x34,0x9e,0xc7,0x55,0x46,0xf5,0x8f,0xb7,0xc2,0x77,0x5c,0x38,0x46,0x2c,0x50,0x10,0xd8,0x46
        };
        all &= check("SHAKE256 empty 114B", out, exp, 114);
    }

    // ---- 增量 squeeze 一致性: 分两次 squeeze 应等于一次 squeeze
    {
        uint8_t once[64], twice[64];
        jpssl::shake256(nullptr, 0, once, 64);
        jpssl::sha3_ctx ctx;
        jpssl::shake256_init(&ctx);
        jpssl::shake_squeeze(&ctx, twice, 20);
        jpssl::shake_squeeze(&ctx, twice + 20, 44);
        all &= check("SHAKE256 incremental squeeze", once, twice, 64);
    }

    printf("\n%s\n", all ? "ALL SHAKE TESTS PASSED" : "SOME SHAKE TESTS FAILED");
    return all ? 0 : 1;
}
