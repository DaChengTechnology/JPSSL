// Direct test: ed25519_verify with RFC 8032 Test 1
#include "ed25519.hpp"
#include <cstdio>
#include <cstring>
using namespace jpssl;

int main() {
    // RFC 8032 Section 7.1 TEST 1
    uint8_t pub[32] = {
        0xd7,0x5a,0x98,0x01,0x82,0xb1,0x0a,0xb7,0xd5,0x4b,0xfe,0xd3,0xc9,0x64,0x07,0x3a,
        0x0e,0xe1,0x72,0xf3,0xda,0xa6,0x23,0x25,0xaf,0x02,0x1a,0x68,0xf7,0x07,0x51,0x1a
    };
    uint8_t sig[64] = {
        0xe5,0x56,0x43,0x00,0xc3,0x60,0xac,0x72,0x90,0x86,0xe2,0xcc,0x80,0x6e,0x82,0x8a,
        0x84,0x87,0x7f,0x1e,0xb8,0xe5,0xd9,0x74,0xd8,0x73,0xe0,0x65,0x22,0x49,0x01,0x55,
        0x5f,0xb8,0x82,0x15,0x90,0xa3,0x3b,0xac,0xc6,0x1e,0x39,0x70,0x1c,0xf9,0xb4,0x6b,
        0xd2,0x5b,0xf5,0xf0,0x59,0x5b,0xbe,0x24,0x65,0x51,0x41,0x43,0x8e,0x7a,0x10,0x0b
    };
    
    // Test with empty message (RFC 8032 Test 1)
    bool ok = ed25519_verify(pub, nullptr, 0, sig);
    printf("ed25519_verify(RFC Test 1, empty msg): %s\n", ok ? "PASS" : "FAIL");
    
    // Also test keygen + sign + verify round-trip
    uint8_t pk2[32], sk2[64];
    ed25519_keygen(pk2, sk2);
    
    const char* msg = "Hello, Ed25519!";
    uint8_t sig2[64];
    ed25519_sign(sk2, (const uint8_t*)msg, strlen(msg), sig2);
    
    bool ok2 = ed25519_verify(pk2, (const uint8_t*)msg, strlen(msg), sig2);
    printf("Round-trip (keygen+sign+verify): %s\n", ok2 ? "PASS" : "FAIL");
    
    // Verify with tampered message should fail
    bool ok3 = ed25519_verify(pk2, (const uint8_t*)"Tampered msg", 12, sig2);
    printf("Verify tampered msg (should FAIL): %s\n", ok3 ? "FAIL (unexpected pass)" : "PASS (correctly rejected)");
    
    return 0;
}
