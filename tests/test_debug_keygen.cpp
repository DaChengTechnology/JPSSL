// Diagnostic: include ed25519.cpp to access internal functions
#include "sha512.hpp"
#include "ed25519.cpp"
#include <cstdio>
#include <cstring>
using namespace jpssl;
using namespace fe_impl;

static void hex(const char* label, const uint8_t* d, int n) {
    printf("%s: ", label);
    for (int i=0;i<n;i++) printf("%02x",d[i]);
    printf("\n");
}

int main() {
    printf("=== Roundtrip: Basepoint encode/decode ===\n");
    const ge_p3* B = ge_get_basepoint();
    uint8_t B_enc[32];
    ge_tobytes(B_enc, B);
    hex("B encoded", B_enc, 32);
    
    // Decode back
    ge_p3 B2;
    int ret = ge_frombytes(&B2, B_enc);
    printf("decode ret: %d\n", ret);
    
    uint8_t B2_enc[32];
    ge_tobytes(B2_enc, &B2);
    hex("B re-encoded", B2_enc, 32);
    printf("Match: %s\n", memcmp(B_enc, B2_enc, 32)==0?"YES":"NO");
    
    printf("\n=== Roundtrip: Pubkey A ===\n");
    uint8_t pub[32] = {0xd7,0x5a,0x98,0x01,0x82,0xb1,0x0a,0xb7,0xd5,0x4b,0xfe,0xd3,0xc9,0x64,0x07,0x3a,0x0e,0xe1,0x72,0xf3,0xda,0xa6,0x23,0x25,0xaf,0x02,0x1a,0x68,0xf7,0x07,0x51,0x1a};
    hex("A (input)", pub, 32);
    ge_p3 A_pt;
    ret = ge_frombytes(&A_pt, pub);
    printf("decode ret: %d\n", ret);
    uint8_t A_enc[32];
    ge_tobytes(A_enc, &A_pt);
    hex("A (re-enc)", A_enc, 32);
    printf("Match: %s\n", memcmp(pub, A_enc, 32)==0?"YES":"NO");
    
    printf("\n=== Roundtrip: R from sig ===\n");
    uint8_t sig[64] = {0xe5,0x56,0x43,0x00,0xc3,0x60,0xac,0x72,0x90,0x86,0xe2,0xcc,0x80,0x6e,0x82,0x8a,0x84,0x87,0x7f,0x1e,0xb8,0xe5,0xd9,0x74,0xd8,0x73,0xe0,0x65,0x22,0x49,0x01,0x55};
    hex("R (input)", sig, 32);
    ge_p3 R_pt;
    ret = ge_frombytes(&R_pt, sig);
    printf("decode ret: %d\n", ret);
    uint8_t R_enc[32];
    ge_tobytes(R_enc, &R_pt);
    hex("R (re-enc)", R_enc, 32);
    printf("Match: %s\n", memcmp(sig, R_enc, 32)==0?"YES":"NO");
    
    // Test: 2 * B using ge_p3_dbl
    printf("\n=== 2*B using ge_p3_dbl ===\n");
    ge_p1p1 t;
    ge_p3_dbl(&t, B);
    ge_p3 B2d;
    ge_p1p1_to_p3(&B2d, &t);
    uint8_t B2_enc2[32];
    ge_tobytes(B2_enc2, &B2d);
    hex("2B (jpssl)", B2_enc2, 32);
    
    // Expected 2B from Python:
    // x=24727413235106541002554574571675588834622768167397638456726423682521233608206
    // y=15549675580280190176352668710449543251562272006154731716076960484076539785455
    uint8_t B2_expected[32] = {
        0x6f,0x6d,0xed,0x8b,0xb2,0xec,0xda,0x5f,
        0xf4,0x3f,0xba,0x82,0x16,0xab,0x46,0x28,
        0x84,0x15,0x16,0x83,0x8b,0xdf,0x66,0x2b,
        0xba,0x0d,0xdb,0x72,0x32,0xa4,0x91,0x3b
    };
    hex("2B expected", B2_expected, 32);
    // The expected has bit7=0, meaning x is even
    
    // Now test S*B with a known scalar
    printf("\n=== k*A (k from RFC test) ===\n");
    uint8_t k[32] = {0x04,0x54,0x52,0x2e,0x16,0x7e,0x3e,0x8a,0x13,0x2c,0xec,0x31,0x61,0x25,0xd8,0xf8,0x6c,0xdf,0x00,0xc6,0xe7,0x04,0x05,0x29,0x3d,0x19,0x96,0x4c,0x8e,0xea,0xbc,0x86};
    hex("k", k, 32);
    
    ge_p3 kA;
    ge_scalarmult(&kA, k, &A_pt);
    uint8_t kA_enc[32];
    ge_tobytes(kA_enc, &kA);
    hex("k*A (jpssl)", kA_enc, 32);
    
    // Expected from Python: 9d890a59a69e9fc6e2901b2f8467fc5cdf215e9965e91e4fc4b5ba332adece0d
    uint8_t kA_expected[32] = {0x0d,0xce,0xde,0x2a,0x33,0xba,0xb5,0xc4,0x4f,0x1e,0xe9,0x65,0x99,0x5e,0x21,0xdf,0x5c,0xfc,0x67,0x84,0x2f,0x1b,0x90,0xe2,0xc6,0x9f,0x9e,0xa6,0x59,0x0a,0x89,0x9d};
    hex("k*A expected", kA_expected, 32);
    
    printf("\n=== S*B (S from RFC test) ===\n");
    uint8_t S[32] = {0x0b,0x10,0x7a,0x8e,0x43,0x41,0x51,0x65,0x24,0xbe,0x5b,0x59,0xf0,0xf5,0x5b,0xd2,0x6b,0xb4,0xf9,0x1c,0x70,0x39,0x1e,0xc6,0xac,0x3b,0xa3,0x90,0x15,0x82,0xb8,0x5f};
    hex("S", S, 32);
    
    ge_p3 SB;
    ge_scalarmult_base(&SB, S);
    uint8_t SB_enc[32];
    ge_tobytes(SB_enc, &SB);
    hex("S*B (jpssl)", SB_enc, 32);
    
    // Expected from Python: 90b0d1a150dbe90444d5dec6d9777631d745e6e4f5c257e373b836ba275e2d86
    uint8_t SB_expected[32] = {0x86,0x2d,0x5e,0x27,0xba,0x36,0xb8,0x73,0xe3,0x57,0xc2,0xf5,0xe4,0xe6,0x45,0xd7,0x31,0x76,0x77,0xd9,0xc6,0xde,0xd5,0x44,0x04,0xe9,0xdb,0x50,0xa1,0xd1,0xb0,0x90};
    hex("S*B expected", SB_expected, 32);
    
    return 0;
}
